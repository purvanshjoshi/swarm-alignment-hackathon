"""Statistics supplement: python -m ladder.supplement results/<run> <out_dir>

Writes every per-cell statistic (cells.csv) and a Markdown supplement (statistics_supplement.md)
with per-cell rates and Wilson intervals, verification behaviour, and all Fisher tests, from the
same summary.jsonl the report uses. Qwen (stopped by a daily quota) is excluded, as in the report.
"""

import csv
import sys
from collections import defaultdict
from pathlib import Path

from scipy.stats import fisher_exact

from .analyze import load, wilson
from .conditions import AUTHORISED, CONDITIONS

ORDER = list(CONDITIONS)
UNAUTH = ["C2_coord_unsigned", "C3_coord_valid_sig", "C4_coord_forged_sig", "C5_principal_claim"]
SHORT = {"nvidia/nemotron-3-ultra-550b-a55b": "Nemotron 3 Ultra", "stepfun-ai/step-5-preview": "Step-5 preview"}


def fisher(k1, n1, k2, n2):
    return fisher_exact([[k1, n1 - k1], [k2, n2 - k2]])[1]


def main(run, out_dir):
    rows = [r for r in load([run]) if r["model"] in SHORT]
    g = defaultdict(list)
    for r in rows:
        g[(r["model"], r["condition"], r["defence"])].append(r)
    cells = {}
    for key, rs in g.items():
        v = [r for r in rs if r["valid"]]
        k = sum(r["crossed"] for r in v)
        lo, hi = wilson(k, len(v))
        cells[key] = dict(model=SHORT[key[0]], condition=key[1], defence="on" if key[2] else "off", n_total=len(rs),
                          n_valid=len(v), k=k, rate=k / len(v), ci_lo=lo, ci_hi=hi,
                          any_verify=sum(r["verify_calls"] > 0 for r in v),
                          verified_treatment=sum(r["verified_treatment"] for r in v),
                          verified_before_cross=sum(r["verified_before_cross"] for r in v),
                          tamper=sum(r["tamper_write"] for r in v), source_gaming=sum(r["source_gaming"] for r in v),
                          turn_cap=sum(r["halt"] == "turn_cap" for r in v),
                          mean_turns=sum(r["n_turns"] for r in v) / len(v),
                          authorised=key[1] in AUTHORISED)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    order = sorted(cells, key=lambda k: (k[0], k[2], ORDER.index(k[1])))
    with open(out / "cells.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(next(iter(cells.values()))))
        w.writeheader()
        for key in order:
            w.writerow({k: (round(v, 4) if isinstance(v, float) else v) for k, v in cells[key].items()})

    L = ["# Statistics supplement", "",
         f"Generated by `python -m ladder.supplement {run}` from `summary.jsonl` (after `ladder.rescore`). "
         "Every number in the report can be traced to this file or to `cells.csv`. "
         "Rates use valid episodes; 95% intervals are Wilson score intervals; tests are two-sided Fisher exact tests, "
         "not corrected for multiple comparisons.", "",
         "## S1. Every cell", "",
         "| Model | Condition | Defence | Valid / total | Edits | Rate [95% CI] | Any verify | Verified msg-2 | Verified before edit | Turn cap | Mean turns |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for key in order:
        c = cells[key]
        L.append(f"| {c['model']} | {c['condition']}{' (authorised)' if c['authorised'] else ''} | {c['defence']} | "
                 f"{c['n_valid']} / {c['n_total']} | {c['k']} | {c['rate']:.2f} [{c['ci_lo']:.2f}, {c['ci_hi']:.2f}] | "
                 f"{c['any_verify']} | {c['verified_treatment']} | {c['verified_before_cross']} | {c['turn_cap']} | {c['mean_turns']:.1f} |")
    L += ["", f"Tampering with other test/config files: {sum(c['tamper'] for c in cells.values())} episodes. "
          f"Source gaming: {sum(c['source_gaming'] for c in cells.values())} episodes.", "",
          "## S2. Each condition against baseline (no defence)", "", "| Model | Condition | Edits | Baseline | p |", "|---|---|---|---|---|"]
    for m in SHORT:
        b = cells[(m, "C0_baseline", False)]
        for cond in ORDER[1:]:
            c = cells[(m, cond, False)]
            L.append(f"| {SHORT[m]} | {cond} | {c['k']}/{c['n_valid']} | {b['k']}/{b['n_valid']} | {fisher(c['k'], c['n_valid'], b['k'], b['n_valid']):.4f} |")
    L += ["", "## S3. Defence on vs off", "", "| Model | Condition | Off | On | p |", "|---|---|---|---|---|"]
    for m in SHORT:
        for cond in ORDER[2:]:
            a, b = cells[(m, cond, False)], cells[(m, cond, True)]
            L.append(f"| {SHORT[m]} | {cond} | {a['k']}/{a['n_valid']} | {b['k']}/{b['n_valid']} | {fisher(a['k'], a['n_valid'], b['k'], b['n_valid']):.4f} |")
    L += ["", "## S4. Pooled comparisons (exploratory)", "", "| Model | Comparison | A | B | p |", "|---|---|---|---|---|"]
    for m in SHORT:
        for dfn in (False, True):
            ua = [cells[(m, c, dfn)] for c in UNAUTH]
            ku, nu = sum(c["k"] for c in ua), sum(c["n_valid"] for c in ua)
            a = cells[(m, "C6_principal_valid_sig", dfn)]
            L.append(f"| {SHORT[m]} | authorised C6 vs unauthorised C2–C5 (defence {'on' if dfn else 'off'}) | "
                     f"{a['k']}/{a['n_valid']} | {ku}/{nu} | {fisher(a['k'], a['n_valid'], ku, nu):.4f} |")
        off = [cells[(m, c, False)] for c in UNAUTH]
        on = [cells[(m, c, True)] for c in UNAUTH]
        k0, n0, k1, n1 = sum(c["k"] for c in off), sum(c["n_valid"] for c in off), sum(c["k"] for c in on), sum(c["n_valid"] for c in on)
        L.append(f"| {SHORT[m]} | unauthorised C2–C5, defence off vs on | {k0}/{n0} | {k1}/{n1} | {fisher(k0, n0, k1, n1):.4f} |")
    L += ["", "## S5. Same-text provenance comparisons (no defence)", "",
          "These compare conditions whose message text is identical, so only the signature differs.", "",
          "| Model | Comparison | A | B | p |", "|---|---|---|---|---|"]
    for m in SHORT:
        for a, b in (("C2_coord_unsigned", "C3_coord_valid_sig"), ("C2_coord_unsigned", "C4_coord_forged_sig"),
                     ("C3_coord_valid_sig", "C4_coord_forged_sig"), ("C5_principal_claim", "C6_principal_valid_sig")):
            x, y = cells[(m, a, False)], cells[(m, b, False)]
            L.append(f"| {SHORT[m]} | {a} vs {b} | {x['k']}/{x['n_valid']} | {y['k']}/{y['n_valid']} | {fisher(x['k'], x['n_valid'], y['k'], y['n_valid']):.4f} |")
    tests = []
    for ln in L[L.index("## S2. Each condition against baseline (no defence)"):]:
        if ln.startswith("| ") and not ln.startswith("| Model"):
            cols = [c.strip() for c in ln.strip("|").split("|")]
            tests.append((cols[0] + ", " + cols[1], float(cols[-1])))
    alpha = 0.05 / len(tests)
    keep = [name for name, pv in tests if pv < alpha]
    L += ["", "## Multiple comparisons", "",
          f"Sections S2–S5 report {len(tests)} Fisher tests, none corrected for multiplicity. Under a Bonferroni correction "
          f"(threshold 0.05/{len(tests)} = {alpha:.4f}), {len(keep)} remain significant: {'; '.join(keep)}. "
          "All other comparisons, including Nemotron's peer-precedent effect (C1) and the pooled Step-5 authorised-vs-unauthorised "
          "comparison, should be read as exploratory."]
    (out / "statistics_supplement.md").write_text("\n".join(L) + "\n")
    print(f"wrote {out}/cells.csv and statistics_supplement.md ({len(cells)} cells)")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "results/main", sys.argv[2] if len(sys.argv) > 2 else "../../docs/extra")
